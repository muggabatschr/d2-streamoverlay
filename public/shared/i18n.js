// Übersetzt einen Schlüssel; {token}-Platzhalter werden aus params ersetzt.
export function t(key, params) {
  const table = DICT[current] || DICT.de;
  let s = table[key] ?? DICT.de[key] ?? DICT.en[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? params[k] : ''));
  return s;
}

// Wendet die aktuelle UI-Sprache auf alle statisch markierten Elemente an:
//   data-i18n            -> textContent
//   data-i18n-title      -> title-Attribut
//   data-i18n-placeholder-> placeholder-Attribut
// Setzt außerdem <html lang>. Wird beim Start und nach jedem UI-Sprachwechsel aufgerufen.
export function applyTranslations(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-title]'))
    node.title = t(node.dataset.i18nTitle);
  for (const node of root.querySelectorAll('[data-i18n-placeholder]'))
    node.placeholder = t(node.dataset.i18nPlaceholder);
  if (root === document || root === document.documentElement) {
    document.documentElement.lang = current;
  }
}
